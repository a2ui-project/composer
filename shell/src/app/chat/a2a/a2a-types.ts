/**
 * Task state lifecycle status token in standard A2A specification.
 * Supports v0.3 lowercase, v1.0 enum names, and Protobuf integer enums.
 */
export type TaskState = A2aV03TaskState | A2aV1TaskState | A2aProtoTaskState | number | string;

/**
 * Mapping from v1.0 protobuf enum names to standardized lowercase display strings.
 */
export const TASK_STATE_DISPLAY: Record<string, string> = {
  TASK_STATE_UNSPECIFIED: 'unspecified',
  TASK_STATE_SUBMITTED: 'submitted',
  TASK_STATE_WORKING: 'working',
  TASK_STATE_COMPLETED: 'completed',
  TASK_STATE_FAILED: 'failed',
  TASK_STATE_CANCELED: 'canceled',
  TASK_STATE_CANCELLED: 'canceled',
  TASK_STATE_INPUT_REQUIRED: 'input-required',
  TASK_STATE_REJECTED: 'rejected',
  TASK_STATE_AUTH_REQUIRED: 'auth-required',
};

/**
 * Mapping from protobuf integer enum values to standardized display strings.
 */
export const TASK_STATE_INT_MAP: Record<number, string> = {
  [A2aProtoTaskState.UNSPECIFIED]: 'unknown',
  [A2aProtoTaskState.SUBMITTED]: 'submitted',
  [A2aProtoTaskState.WORKING]: 'working',
  [A2aProtoTaskState.COMPLETED]: 'completed',
  [A2aProtoTaskState.FAILED]: 'failed',
  [A2aProtoTaskState.CANCELED]: 'canceled',
  [A2aProtoTaskState.INPUT_REQUIRED]: 'input-required',
  [A2aProtoTaskState.REJECTED]: 'rejected',
  [A2aProtoTaskState.AUTH_REQUIRED]: 'auth-required',
};

/**
 * Terminal states that signal an A2A task or stream is completed in Protobuf enum integer representation.
 */
export const TERMINAL_PROTO_TASK_STATES: ReadonlySet<A2aProtoTaskState> = new Set([
  A2aProtoTaskState.COMPLETED,
  A2aProtoTaskState.FAILED,
  A2aProtoTaskState.CANCELED,
  A2aProtoTaskState.REJECTED,
]);

/**
 * Normalizes any TaskState representation (v1.0 enum name, Protobuf integer, or v0.3 lowercase)
 * into a consistent lowercase string for UI display and status checks.
 */
export function normalizeTaskState(state: unknown): string {
  if (state === undefined || state === null) return 'unknown';
  if (typeof state === 'number') {
    return TASK_STATE_INT_MAP[state] || String(state);
  }
  const str = String(state).trim();
  if (!str) return 'unknown';
  const numericVal = Number(str);
  if (!isNaN(numericVal) && numericVal in TASK_STATE_INT_MAP) {
    return TASK_STATE_INT_MAP[numericVal];
  }
  if (TASK_STATE_DISPLAY[str]) {
    return TASK_STATE_DISPLAY[str];
  }
  const upper = str.toUpperCase();
  if (TASK_STATE_DISPLAY[upper]) {
    return TASK_STATE_DISPLAY[upper];
  }
  return str.toLowerCase();
}

/**
 * Terminal states that signal an A2A task or stream is completed.
 */
export const TERMINAL_TASK_STATES: ReadonlySet<string> = new Set([
  'completed',
  'canceled',
  'cancelled',
  'failed',
  'rejected',
  'success',
  'done',
  'task_state_completed',
  'task_state_canceled',
  'task_state_cancelled',
  'task_state_failed',
  'task_state_rejected',
]);

/**
 * Checks whether a given task status, state, or event represents a terminal state.
 *
 * Robustly normalizes Protobuf enum integers, enum strings, and event objects
 * into standardized terminal states without fragile hardcoded numbers.
 */
export function isTerminalTaskState(stateOrEvent: unknown): boolean {
  if (stateOrEvent === undefined || stateOrEvent === null) return false;
  if (typeof stateOrEvent === 'object') {
    const obj = stateOrEvent as Record<string, unknown>;
    if (obj['final'] === true || obj['isCompleted'] === true) {
      return true;
    }
    if ('status' in obj) {
      const rawStatus = obj['status'];
      const rawState =
        typeof rawStatus === 'object' && rawStatus !== null
          ? (rawStatus as Record<string, unknown>)['state']
          : rawStatus;
      return isTerminalTaskState(rawState);
    }
    return false;
  }
  const normalized = normalizeTaskState(stateOrEvent);
  return TERMINAL_TASK_STATES.has(normalized);
}

/**
 * Event stream chunk emitted during A2A streaming execution.
 *
 * Supports both camelCase (v0.3 / TypeScript JSON) and snake_case (v1.0 Protobuf
 * / Python SDKs) field names, as well as Protobuf StreamResponse oneof wrappers
 * (`task`, `status_update`, `artifact_update`).
 */
export interface TaskStatusUpdateEvent {
  kind?: 'task' | 'status-update' | 'artifact-update' | 'message' | string;
  id?: string;
  taskId?: string;
  task_id?: string;
  contextId?: string;
  context_id?: string;
  message?: A2aMessage;
  parts?: A2aPart[];
  status?:
    | {
        state?: TaskState;
        message?: string | A2aMessage;
        [key: string]: unknown;
      }
    | string;
  artifact?: A2aArtifact;
  artifacts?: A2aArtifact[];
  final?: boolean;
  error?: string;
  validation_errors?: string[];
  validationErrors?: string[];
  // Protobuf StreamResponse oneof payload wrappers
  task?: Record<string, unknown>;
  status_update?: Record<string, unknown>;
  statusUpdate?: Record<string, unknown>;
  artifact_update?: Record<string, unknown>;
  artifactUpdate?: Record<string, unknown>;
  [key: string]: unknown;
}

/**
 * Options passed to A2A transport calls.
 */
export interface A2aTransportOptions {
  contextId?: string;
  taskId?: string;
  tenantId?: string;
  headers?: Record<string, string>;
  abortSignal?: AbortSignal;
}

/**
 * Transport contract interface for A2A communication.
 */
export interface A2aTransport {
  /**
   * Retrieves the AgentCard from the target endpoint.
   */
  getAgentCard(baseUrl: string, options?: A2aTransportOptions): Promise<AgentCard>;

  /**
   * Streams conversational message turns and task updates from the target endpoint.
   */
  sendMessageStream(
    baseUrl: string,
    message: A2aMessage,
    options?: A2aTransportOptions,
  ): AsyncIterable<TaskStatusUpdateEvent>;

  /**
   * Dispatches interactive user action payload back to the target agent task.
   */
  sendActionStream(
    baseUrl: string,
    taskId: string,
    action: unknown,
    options?: A2aTransportOptions,
  ): AsyncIterable<TaskStatusUpdateEvent>;
}
