/**
 * A discrete skill, tool, or capability exposed by an A2A Agent.
 */
export interface AgentSkill {
  /** Unique skill identifier. */
  id: string;
  /** Human-readable skill name. */
  name: string;
  /** Description of what this skill does. */
  description?: string;
  /** Specific input modalities accepted by this skill (e.g. 'text', 'audio', 'image'). */
  inputModes?: string[];
  /** Specific output modalities produced by this skill (e.g. 'text', 'application/json+a2ui'). */
  outputModes?: string[];
  [key: string]: unknown;
}

/**
 * Declared capabilities of an A2A Agent.
 */
export interface AgentCapability {
  /** Indicates whether the agent supports SSE streaming responses. */
  streaming?: boolean;
  /** Indicates whether the agent supports asynchronous push notifications. */
  pushNotifications?: boolean;
  /** Custom protocol extensions supported by the agent. */
  extensions?: Array<{
    uri: string;
    description?: string;
    [key: string]: unknown;
  }>;
  [key: string]: unknown;
}

/**
 * Supported network interface exposed by an A2A Agent (v1.0 specification).
 */
export interface AgentInterface {
  /** Target service endpoint URL for this interface. */
  url: string;
  /** Primary protocol binding (e.g. 'JSONRPC', 'HTTP_JSON', 'GRPC'). */
  protocolBinding?: string;
  /** Legacy protocol transport string (e.g. 'JSONRPC'). */
  transport?: string;
  [key: string]: unknown;
}

/**
 * Specification schema for an AgentCard manifest published by an A2A compliant service.
 * Supports both v0.3 (top-level 'url') and v1.0 ('supportedInterfaces') schemas.
 */
export interface AgentCard {
  /** Target service URL if different from discovery endpoint (v0.3 format). */
  url?: string;
  /** Supported protocol interfaces and endpoints exposed by the agent (v1.0 format). */
  supportedInterfaces?: AgentInterface[];
  /** Protobuf snake_case alias for supportedInterfaces. */
  supported_interfaces?: AgentInterface[];
  /** Preferred transport protocol if specified (v0.3 format). */
  preferredTransport?: string;
  /** Protobuf snake_case alias for preferredTransport. */
  preferred_transport?: string;
  /** Display name of the agent. */
  name: string;
  /** High-level description of the agent's purpose and functionality. */
  description?: string;
  /** Semantic version string of the agent service. */
  version?: string;
  /** URL to the agent's icon or avatar image. */
  iconUrl?: string;
  /** Protobuf snake_case alias for iconUrl. */
  icon_url?: string;
  /** URL to external documentation or home page for the agent. */
  documentationUrl?: string;
  /** Protobuf snake_case alias for documentationUrl. */
  documentation_url?: string;
  /** Declared protocol capabilities of the agent. */
  capabilities?: AgentCapability;
  /** Default input modalities accepted by the agent (e.g. 'text', 'image'). */
  defaultInputModes?: string[];
  /** Protobuf snake_case alias for defaultInputModes. */
  default_input_modes?: string[];
  /** Default output modalities generated by the agent (e.g. 'text', 'application/json+a2ui'). */
  defaultOutputModes?: string[];
  /** Protobuf snake_case alias for defaultOutputModes. */
  default_output_modes?: string[];
  /** Array of discrete skills/tools exposed by the agent. */
  skills?: AgentSkill[];
  /** Suggested starter prompts or queries for interacting with the agent. */
  samplePrompts?: string[];
  /** Protobuf snake_case alias for samplePrompts. */
  sample_prompts?: string[];
}

/**
 * Tool call invocation inside an A2A message turn.
 */
export interface A2aToolCall {
  name: string;
  id?: string;
  args?: Record<string, unknown>;
  [key: string]: unknown;
}

/**
 * Tool result return inside an A2A message turn.
 */
export interface A2aToolResult {
  name?: string;
  id?: string;
  result?: unknown;
  error?: string;
  [key: string]: unknown;
}

/**
 * Artifact payload attached or generated in an A2A task.
 */
export interface A2aArtifact {
  id?: string;
  artifactId?: string;
  name?: string;
  description?: string;
  metadata?: Record<string, unknown>;
  parts?: A2aPart[];
  [key: string]: unknown;
}

/**
 * Single content part of an A2A message turn.
 *
 * Supports both v0.3 and v1.0 part formats:
 * - Text part: { text: string }
 * - File (URI): { url: string, mediaType?: string, filename?: string }
 * - File (raw bytes base64): { raw: string, mediaType?: string, filename?: string }
 * - File (v0.3 nested): { file: { uri?: string, bytes?: string, mimeType?: string, name?: string } }
 * - Data part: { data: object }
 */
export interface A2aPart {
  /** Text content (v0.3 / v1.0). */
  text?: string;
  /** File URI oneof (v1.0 flat format). */
  url?: string;
  /** Raw file bytes encoded as base64 (v1.0 flat format). */
  raw?: string;
  /** MIME/Media type for file or data parts (v1.0 camelCase). */
  mediaType?: string;
  /** Protobuf snake_case alias for mediaType. */
  media_type?: string;
  /** Standard MIME type alias. */
  mimeType?: string;
  /** Filename for attached file parts (v1.0). */
  filename?: string;
  /** Model reasoning or thought content. */
  thought?: string;
  /** Explicit kind discriminator. */
  kind?: string;
  /** File part nested payload (v0.3 format). */
  file?: {
    name?: string;
    mimeType?: string;
    data?: string; // base64 encoded
    bytes?: string;
    uri?: string;
    [key: string]: unknown;
  };
  /** Structured data or A2UI component item payload. */
  data?: Record<string, unknown>;
  /** Discrete tool invocation. */
  toolCall?: A2aToolCall;
  /** Discrete tool execution return. */
  toolResult?: A2aToolResult;
  /** Attached artifact payload. */
  artifact?: A2aArtifact;
  /** Optional metadata associated with the part. */
  metadata?: Record<string, unknown>;
  [key: string]: unknown;
}

/**
 * Message object exchanged within an A2A task session.
 */
export interface A2aMessage {
  role: 'user' | 'agent' | 'assistant' | 'system' | 'ROLE_USER' | 'ROLE_AGENT' | string;
  parts: A2aPart[];
  contextId?: string;
  context_id?: string;
  taskId?: string;
  task_id?: string;
  messageId?: string;
  message_id?: string;
  metadata?: Record<string, unknown>;
}

